export function fetchParts({ category, brands, priceRange, sort } = {}) {
  let list = [...parts]

  if (category && category !== 'all') {
    list = list.filter((p) => p.category === category)
  }
  if (brands && brands.length) {
    list = list.filter((p) => brands.includes(p.brand))
  }
  if (priceRange) {
    const [min, max] = priceRange
    list = list.filter((p) => p.price >= min && p.price <= (max || Infinity))
  }
  if (sort === 'price-asc') list.sort((a, b) => a.price - b.price)
  if (sort === 'price-desc') list.sort((a, b) => b.price - a.price)
  if (sort === 'rating') list.sort((a, b) => b.rating - a.rating)
  // 按发布时间从新到旧（released 格式为 'YYYY-MM'，字符串可直接比较）
  if (sort === 'newest') list.sort((a, b) => (b.released || '').localeCompare(a.released))

  return list
}

// 返回某分类下的所有品牌（用于筛选栏）
export function getBrands(category) {
  const source = category && category !== 'all' ? parts.filter((p) => p.category === category) : parts
  return [...new Set(source.map((p) => p.brand))]
}

// 根据 id 查找单个配件
export function findPartById(id) {
  return parts.find((p) => p.id === id) || null
}

